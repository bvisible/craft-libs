#!/usr/bin/env python3
# //// Neoffice — added file (no upstream equivalent): generates src/orb_rings.rs from the design system's Nora orb.
"""Reads `assets/icons/nora-orb.svg` of the Neoffice design system (bvisible/neoffice-design-system) and writes the
geometry of its thirteen rings of dust as a Rust table, so that the pane draws the very sphere the desk draws, not a
look-alike. Run: python3 gen_orb.py <path to nora-orb.svg> > ../src/orb_rings.rs"""
import re
import sys

svg = open(sys.argv[1], encoding="utf-8").read()
rings = {}
for m in re.finditer(r"<path class=\"(front|back) r(\d+)\"([^>]*)/>", svg):
    side, index, attrs = m.group(1), int(m.group(2)), m.group(3)
    get = lambda name: re.search(name + r'="([^"]*)"', attrs).group(1)
    rotate = float(re.match(r"rotate\(([-\d.]+) ", get("transform")).group(1))
    width = float(get("stroke-width"))
    d = get("d")
    nums = [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", d)]
    x0, y0, rx, ry = nums[0], nums[1], nums[2], nums[3]
    x1 = nums[-2]
    dashes = [float(x) for x in get("stroke-dasharray").split()]
    offset = float(get("stroke-dashoffset"))
    ring = rings.setdefault(index, {})
    ring.update(rotate=rotate, width=width, cx=(x0 + x1) / 2, cy=y0, rx=rx, ry=ry, dashes=dashes)
    ring[side + "_offset"] = offset
duration = {int(i): float(s) for i, s in re.findall(r"\.r(\d+)\{animation-duration:([\d.]+)s\}", svg)}

print("// //// Neoffice — added file (no upstream equivalent): GENERATED by tools/gen_orb.py from the design system's")
print("// assets/icons/nora-orb.svg (bvisible/neoffice-design-system). Do not edit by hand.")
print()
print("use super::orb::Ring;")
print()
print("pub(super) const RINGS: [Ring; %d] = [" % len(rings))
for i in sorted(rings):
    r = rings[i]
    # The dots sit where a dash of 0.01 starts: the running sums of the pattern at even positions.
    starts, at = [], 0.0
    for k, length in enumerate(r["dashes"]):
        if k % 2 == 0:
            starts.append(round(at, 4))
        at += length
    print("    Ring {")
    print("        rotate: %s," % r["rotate"])
    print("        width: %s," % r["width"])
    print("        cx: %s," % round(r["cx"], 3))
    print("        cy: %s," % r["cy"])
    print("        rx: %s," % r["rx"])
    print("        ry: %s," % r["ry"])
    print("        period: %s," % round(at, 4))
    print("        starts: &%s," % starts)
    print("        front_offset: %s," % r["front_offset"])
    print("        back_offset: %s," % r["back_offset"])
    print("        seconds: %s," % duration[i])
    print("    },")
print("];")
